/**
 * Generates `electron/main/voice/model-manifest.ts` — the exact, pinned
 * recipe the model manager (and the smoke test) uses to fetch voice
 * models. Every entry records:
 *   - the HuggingFace repo + immutable revision (commit sha),
 *   - one canonical resolve URL per file (pinned to that commit),
 *   - the file size, a required flag, and the SHA-256 of the content
 *     (for LFS files the checksum is read straight from the repo's LFS
 *     metadata; for plain files it is computed here by downloading and
 *     hashing the bytes once, at manifest-authoring time).
 *
 * Re-run to refresh: `node scripts/voice-model-manifest.mjs`.
 * The output is human-auditable generated data — review the diff.
 */

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const HF_API = "https://huggingface.co/api/models";
// STT: streaming zipformer trained on LibriSpeech AND GigaSpeech (10k h,
// podcasts/YouTube/audiobooks) — the English streaming upgrade of the
// original LibriSpeech-only 2023-06-26 pin (root cause of the physical
// conversational STT failures). Same zipformer2 OnlineRecognizer family.
const STT_REPO = "csukuangfj/sherpa-onnx-streaming-zipformer-en-2023-06-21";
const TTS_REPO = "csukuangfj/kokoro-int8-multi-lang-v1_1";

/** Files we intentionally snapshot (never the .py/.sh/.gitattributes). */
const STT_FILES = new Set([
  "tokens.txt",
  "encoder-epoch-99-avg-1.int8.onnx",
  "decoder-epoch-99-avg-1.int8.onnx",
  "joiner-epoch-99-avg-1.int8.onnx",
  "test_wavs/0.wav",
  "test_wavs/1.wav",
  "test_wavs/8k.wav",
  "test_wavs/trans.txt",
]);
const TTS_FILES = new Set([
  "model.int8.onnx",
  "tokens.txt",
  "voices.bin",
  "lexicon-us-en.txt",
  "lexicon-gb-en.txt",
  "lexicon-zh.txt",
  "date-zh.fst",
  "number-zh.fst",
  "phone-zh.fst",
  "LICENSE",
]);
const TTS_PREFIXES = ["espeak-ng-data/"];

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> HTTP ${res.status}`);
  return res.json();
}

async function sha256OfUrl(url, sizeLimit) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> HTTP ${res.status}`);
  const buffer = Buffer.from(await res.arrayBuffer());
  if (buffer.length !== sizeLimit) {
    throw new Error(`size mismatch for ${url}: ${buffer.length} != ${sizeLimit}`);
  }
  return createHash("sha256").update(buffer).digest("hex");
}

async function hashAllPlain(entries, log) {
  const CONCURRENCY = 8;
  const queue = [...entries];
  const workers = Array.from({ length: CONCURRENCY }, async () => {
    for (;;) {
      const entry = queue.shift();
      if (!entry) return;
      entry.sha256 = await sha256OfUrl(entry.url, entry.size);
      log(`hashed ${entry.path}`);
    }
  });
  await Promise.all(workers);
}

async function collect(repo, suffixFilter, log) {
  const meta = await fetchJson(`${HF_API}/${repo}`);
  const commit = meta.sha;
  const tree = await fetchJson(`${HF_API}/${repo}/tree/${commit}?recursive=true`);
  const files = tree.filter(
    (f) => f.type === "file" && suffixFilter(f),
  );
  log(`${repo} @ ${commit}: ${files.length} files selected`);
  const entries = files.map((f) => ({
    path: f.path,
    size: f.size,
    url: `https://huggingface.co/${repo}/resolve/${commit}/${f.path}`,
    sha256: f.lfs ? f.lfs.oid : null,
  }));
  const plain = entries.filter((e) => e.sha256 === null);
  log(`${repo}: hashing ${plain.length} non-LFS files...`);
  await hashAllPlain(plain, log);
  return { commit, entries };
}

function emit(name, modelKind, data, lines) {
  lines.push(
    "",
    `/* ${name} — pinned at HuggingFace commit ${data.commit}. */`,
    `export const ${name}: PinnedModel = {`,
    `  id: "${modelKind}",`,
    `  repo: "${data.repo}",`,
    `  commit: "${data.commit}",`,
    `  files: [`,
    ...data.entries
      .filter((e) => !e.smoke)
      .map(
        (e) =>
          `    { path: ${JSON.stringify(e.path)}, url: ${JSON.stringify(e.url)}, size: ${e.size}, sha256: ${JSON.stringify(e.sha256)} },`,
      ),
    `  ],`,
    `  smokeFiles: [`,
    ...data.entries
      .filter((e) => e.smoke)
      .map(
        (e) =>
          `    { path: ${JSON.stringify(e.path)}, url: ${JSON.stringify(e.url)}, size: ${e.size}, sha256: ${JSON.stringify(e.sha256)} },`,
      ),
    `  ],`,
    `};`,
  );
}

// eslint-disable-next-line no-alert
console.log("Pinning voice model manifest...");

const sttData = await collect(
  STT_REPO,
  (f) => STT_FILES.has(f.path),
  (m) => console.log(m),
);
sttData.repo = STT_REPO;
for (const e of sttData.entries) {
  e.smoke = e.path.startsWith("test_wavs/");
}

const ttsData = await collect(
  TTS_REPO,
  (f) =>
    TTS_FILES.has(f.path) ||
    TTS_PREFIXES.some((prefix) => f.path.startsWith(prefix)),
  (m) => console.log(m),
);
ttsData.repo = TTS_REPO;

const outPath = join("electron", "main", "voice", "model-manifest.ts");
const header = `/**
 * GENERATED by scripts/voice-model-manifest.mjs — do not edit by hand.
 *
 * Pinned voice model recipes. Each file row carries the immutable
 * HuggingFace resolve URL (frozen at the recorded commit), the exact
 * byte size, and the SHA-256 the model manager verifies BEFORE the file
 * is accepted (downloaded to a temp file, hashed, then atomically
 * renamed). Smoke-test assets (bundled test wavs with ground-truth
 * transcripts) are kept in \`smokeFiles\` and are never required to run
 * the engine.
 */
`;

const types = [
  "export type PinnedModelFile = {",
  "  /** Path relative to the models/<id> directory. */",
  "  path: string;",
  "  /** Immutable resolve URL (frozen at the pinned commit). */",
  "  url: string;",
  "  size: number;",
  "  sha256: string;",
  "};",
  "",
  "export type PinnedModel = {",
  '  /** The model directory name under the models root. */',
  "  id: string;",
  "  repo: string;",
  "  commit: string;",
  "  files: PinnedModelFile[];",
  "  /** Runtime-inert assets (test audio, transcripts) for the smoke test. */",
  "  smokeFiles: PinnedModelFile[];",
  "};",
];

const lines = [header, ...types];
emit("STT_ZIPFORMER_EN_INT8", "stt-zipformer-en-2023-06-21-int8", sttData, lines);
emit("TTS_KOKORO_V11_INT8", "tts-kokoro-multi-lang-v1_1-int8", ttsData, lines);
lines.push(`\nexport const MODEL_TIMESTAMPS = { generatedInIso: ${JSON.stringify(new Date().toISOString())} } as const;\n`);

writeFileSync(outPath, lines.join("\n"), "utf8");
const totalBytes =
  [...sttData.entries, ...ttsData.entries].reduce((a, e) => a + e.size, 0);
console.log(
  `Wrote ${outPath}: ${sttData.entries.length} STT files + ${ttsData.entries.length} TTS files, ${(totalBytes / 1048576).toFixed(1)} MB total.`,
);
