type ChatResponseWire = {
  conversation_id: string;
  response: string;
  status: ChatExchangeStatus;
  timestamp?: string;
  action?: ProposedActionWire | null;
  tool_result?: ExecutedActionWire | null;
  plan?: TaskPlanWire | null;
};

type ProposedActionWire = {
  approval_id: string;
  tool_name: string;
  arguments?: Record<string, unknown> | null;
  action_description: string;
  risk_level: RiskLevelView;
  approval_status: ApprovalStatusView;
  expires_at: string;
};

type ExecutedActionWire = {
  tool_name: string;
  status: "success" | "already_exists" | "failure";
  success: boolean;
  message: string;
};

type TaskPlanWire = {
  plan_id: string;
  goal: string;
  steps: PlanStepWire[];
};

type PlanStepWire = {
  step_id: string;
  description: string;
  tool_name: string;
  status?: PlanStepStatusView;
  depends_on?: string[];
  approval_id?: string | null;
};

export function isChatResponseWire(value: unknown): value is ChatResponseWire {
  if (
    !isRecord(value) ||
    typeof value["conversation_id"] !== "string" ||
    !CONVERSATION_ID_PATTERN.test(value["conversation_id"]) ||
    typeof value["response"] !== "string" ||
    value["response"].length > MAX_TEXT_LENGTH
  ) {
    return false;
  }
  const status = value["status"];
  if (typeof status !== "string" || !EXCHANGE_STATUSES.has(status)) return false;
  const timestamp = value["timestamp"];
  if (timestamp !== undefined && typeof timestamp !== "string") return false;

  const toolResult = value["tool_result"];
  if (toolResult !== undefined && toolResult !== null && !isExecutedActionWire(toolResult)) {
    return false;
  }
  const action = value["action"];
  if (action !== undefined && action !== null && !isProposedActionWire(action)) return false;
  const plan = value["plan"];
  if (plan !== undefined && plan !== null && !isTaskPlanWire(plan)) return false;
  return true;
}

function isProposedActionWire(value: unknown): value is ProposedActionWire {
  if (!isRecord(value)) return false;
  const risk = value["risk_level"];
  const approvalStatus = value["approval_status"];
  const args = value["arguments"];
  return (
    isBoundedString(value["approval_id"], 64) &&
    typeof value["tool_name"] === "string" &&
    value["tool_name"].length > 0 &&
    (args === undefined || args === null || isBoundedArguments(args)) &&
    typeof value["action_description"] === "string" &&
    value["action_description"].length <= 512 &&
    typeof risk === "string" &&
    RISK_LEVELS.has(risk) &&
    typeof approvalStatus === "string" &&
    APPROVAL_STATUSES.has(approvalStatus) &&
    typeof value["expires_at"] === "string"
  );
}

/** Backend bounds proposal arguments at 32 entries; mirror that ceiling. */
function isBoundedArguments(args: unknown): args is Record<string, unknown> {
  return isRecord(args) && Object.keys(args).length <= MAX_ACTION_ARGUMENTS;
}

function isExecutedActionWire(value: unknown): value is ExecutedActionWire {
  if (!isRecord(value)) return false;
  const status = value["status"];
  return (
    typeof value["tool_name"] === "string" &&
    value["tool_name"].length > 0 &&
    typeof status === "string" &&
    TOOL_RESULT_STATUSES.has(status) &&
    typeof value["success"] === "boolean" &&
    typeof value["message"] === "string" &&
    value["message"].length <= 512
  );
}

function isTaskPlanWire(value: unknown): value is TaskPlanWire {
  if (
    !isRecord(value) ||
    !isBoundedString(value["plan_id"], 64) ||
    typeof value["goal"] !== "string" ||
    value["goal"].length > 512
  ) {
    return false;
  }
  const steps = value["steps"];
  if (!Array.isArray(steps) || steps.length > MAX_PLAN_STEPS) return false;
  return steps.every((step) => isPlanStepWire(step));
}

function isPlanStepWire(value: unknown): value is PlanStepWire {
  if (
    !isRecord(value) ||
    !isBoundedString(value["step_id"], 32) ||
    typeof value["description"] !== "string" ||
    value["description"].length > 512 ||
    typeof value["tool_name"] !== "string" ||
    value["tool_name"].length > 64
  ) {
    return false;
  }
  const status = value["status"];
  if (status !== undefined && !(typeof status === "string" && PLAN_STEP_STATUSES.has(status))) {
    return false;
  }
  const dependsOn = value["depends_on"];
  if (
    dependsOn !== undefined &&
    !(Array.isArray(dependsOn) && dependsOn.every((id) => typeof id === "string"))
  ) {
    return false;
  }
  const approvalId = value["approval_id"];
  if (approvalId !== undefined && approvalId !== null && typeof approvalId !== "string") {
    return false;
  }
  return true;
}

type ConversationSummaryWire = {
  conversation_id: string;
  created_at: string;
  updated_at: string;
  turn_count: number;
};

type ConversationListWire = {
  conversations: ConversationSummaryWire[];
  total: number;
  limit: number;
  offset: number;
};

type ConversationHistoryWire = {
  conversation_id: string;
  turns: ConversationTurnWire[];
  turn_count: number;
  total_turn_count: number;
};type ConversationTurnWire = {
  role: "user" | "assistant";
  content: string;
  timestamp: string;
};

type ConversationClearWire = {
  conversation_id: string;
  status?: string;
};

function isConversationSummaryWire(value: unknown): value is ConversationSummaryWire {
  return (
    isRecord(value) &&
    typeof value["conversation_id"] === "string" &&
    CONVERSATION_ID_PATTERN.test(value["conversation_id"]) &&
    typeof value["created_at"] === "string" &&
    typeof value["updated_at"] === "string" &&
    isBoundedInt(value["turn_count"], 0, Number.MAX_SAFE_INTEGER)
  );
}

export function isConversationListWire(value: unknown): value is ConversationListWire {
  if (!isRecord(value) || !isBoundedInt(value["total"], 0, Number.MAX_SAFE_INTEGER)) return false;
  const conversations = value["conversations"];
  if (!Array.isArray(conversations) || conversations.length > MAX_LIST_CONVERSATIONS) return false;
  if (!conversations.every((item) => isConversationSummaryWire(item))) return false;
  return isBoundedInt(value["limit"], 1, Number.MAX_SAFE_INTEGER) && isBoundedInt(value["offset"], 0, Number.MAX_SAFE_INTEGER);
}

function isConversationTurnWire(value: unknown): value is ConversationTurnWire {
  return (
    isRecord(value) &&
    (value["role"] === "user" || value["role"] === "assistant") &&
    typeof value["content"] === "string" &&
    value["content"].length <= MAX_TEXT_LENGTH &&
    typeof value["timestamp"] === "string"
  );
}

export function isConversationHistoryWire(value: unknown): value is ConversationHistoryWire {
  if (
    !isRecord(value) ||
    typeof value["conversation_id"] !== "string" ||
    !CONVERSATION_ID_PATTERN.test(value["conversation_id"])
  ) {
    return false;
  }
  const turns = value["turns"];
  if (!Array.isArray(turns) || turns.length > MAX_HISTORY_TURNS) return false;
  if (!turns.every((turn) => isConversationTurnWire(turn))) return false;
  return (
    isBoundedInt(value["turn_count"], 0, MAX_HISTORY_TURNS) &&
    isBoundedInt(value["total_turn_count"], 0, Number.MAX_SAFE_INTEGER)
  );
}

export function isConversationClearWire(value: unknown): value is ConversationClearWire {
  return (
    isRecord(value) &&
    typeof value["conversation_id"] === "string" &&
    CONVERSATION_ID_PATTERN.test(value["conversation_id"]) &&
    (value["status"] === undefined || value["status"] === "deleted")
  );
}

