/**
 * Pure header builder — the exact header contract the backend expects
 * (backend/app/core/security.py): bearer token + explicit session.
 */
export function buildRequestHeaders(
  token: string | null,
  sessionId: string,
  requestId: string,
): Record<string, string> {
  const headers: Record<string, string> = {
    "X-JARVIS-Session": sessionId,
    "X-Request-ID": requestId,
    Accept: "application/json",
  };
  if (token) headers.Authorization = `Bearer ${token}`;
  return headers;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isBoundedString(value: unknown, max: number): value is string {
  return typeof value === "string" && value.length > 0 && value.length <= max;
}

function isBoundedInt(value: unknown, min: number, max: number): value is number {
  return (
    typeof value === "number" &&
    Number.isInteger(value) &&
    value >= min &&
    value <= max
  );
}

/** True when a JSON object looks like the documented health payload. */
