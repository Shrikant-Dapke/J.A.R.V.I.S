/**
 * Backend API client — MAIN PROCESS ONLY.
 *
 * Every renderer request travels through IPC to this module. It:
 *  - talks ONLY to a validated loopback http(s) origin (net.ts),
 *  - attaches the bearer token and the explicit session header in the
 *    main process (the token never crosses the IPC bridge),
 *  - sends no Origin header (native client; backend require_safe_origin
 *    treats absent Origin as allowed),
 *  - bounds every call with a wall-clock timeout (AbortSignal),
 *  - maps failures to the shared IpcResult envelope with honest codes,
 *  - validates response shapes before anything reaches the renderer.
 *
 * Full response types come from the committed OpenAPI snapshot
 * (electron/api/schema.gen.ts, generated by `npm run generate:api`).
 * Phase 6.1 consumes GET /api/health and GET /api/system-info; further
 * endpoints are wired in later phases on the same client.
 */

import type { paths } from "./schema.gen";
import {
  ipcError,
  ipcOk,
  type HealthCheck,
  type HealthSnapshot,
  type IpcErrorCode,
  type IpcResult,
  type SystemInfoSummary,
} from "../../../shared/ipc-contract";
import { isLoopbackHttpUrl } from "../net";

/** The generated contract surface is re-exported for future phases. */
export type BackendOpenApiPaths = paths;

export type ClientDeps = {
  baseUrl: URL;
  token: string | null;
  sessionId: string;
  requestId?: () => string;
  fetchImpl?: typeof fetch;
  now?: () => number;
};

export const DEFAULT_HEALTH_TIMEOUT_MS = 8_000;
export const DEFAULT_SYSTEM_INFO_TIMEOUT_MS = 15_000;

const MAX_DATA_ITEMS = 32;
const SAFE_MESSAGE_LIMIT = 200;

/**
 * Pure header builder — the exact header contract the backend expects
 * (backend/app/core/security.py): bearer token + explicit session.
 */
export function buildRequestHeaders(
  token: string | null,
  sessionId: string,
  requestId: string,
): Record<string, string> {
  const headers: Record<string, string> = {
    "X-JARVIS-Session": sessionId,
    "X-Request-ID": requestId,
    Accept: "application/json",
  };
  if (token) headers.Authorization = `Bearer ${token}`;
  return headers;
}

/** True when a JSON object looks like the documented health payload. */
export function isHealthSnapshot(value: unknown): value is HealthSnapshot {
  if (typeof value !== "object" || value === null) return false;
  const record = value as Record<string, unknown>;
  return (
    typeof record["name"] === "string" &&
    record["name"].length > 0 &&
    typeof record["status"] === "string" &&
    record["status"].length > 0 &&
    typeof record["version"] === "string" &&
    record["version"].length > 0
  );
}

/** True when a JSON object matches the documented ToolResult shape (wire names). */
type SystemInfoWire = {
  tool_name: string;
  status: "success" | "already_exists" | "failure";
  success: boolean;
  message: string;
  data: Record<string, string> | null;
  timestamp: string;
};

export function isSystemInfoResult(value: unknown): value is SystemInfoWire {
  if (typeof value !== "object" || value === null) return false;
  const record = value as Record<string, unknown>;
  const status = record["status"];
  if (
    typeof record["tool_name"] !== "string" ||
    record["tool_name"].length === 0 ||
    (status !== "success" && status !== "already_exists" && status !== "failure") ||
    typeof record["success"] !== "boolean" ||
    typeof record["message"] !== "string" ||
    typeof record["timestamp"] !== "string"
  ) {
    return false;
  }
  const data = record["data"];
  if (data === null || data === undefined) return true;
  if (typeof data !== "object" || Array.isArray(data)) return false;
  const entries = Object.entries(data as Record<string, unknown>);
  if (entries.length > MAX_DATA_ITEMS) return false;
  return entries.every(
    ([key, item]) => typeof key === "string" && typeof item === "string",
  );
}

function toSummary(raw: SystemInfoWire): SystemInfoSummary {
  return {
    toolName: raw.tool_name,
    status: raw.status,
    success: raw.success,
    message: raw.message,
    data: raw.data ?? null,
    timestamp: raw.timestamp,
  };
}

/** Clamp any exception text into a bounded, safe message. */
function safeMessage(error: unknown): string {
  const text =
    error instanceof Error ? error.message : typeof error === "string" ? error : "unknown error";
  return text.length > SAFE_MESSAGE_LIMIT ? `${text.slice(0, SAFE_MESSAGE_LIMIT)}…` : text;
}

function failureFromException(error: unknown): IpcResult<never> {
  if (error instanceof Error && error.name === "AbortError") {
    return ipcError("TIMEOUT", "The backend did not respond in time.");
  }
  if (error instanceof TypeError) {
    return ipcError("BACKEND_UNREACHABLE", "JARVIS backend is unreachable.");
  }
  return ipcError("UNEXPECTED", `Unexpected client failure: ${safeMessage(error)}`);
}

/** Extract the backend's structured error message (bounded, no internals). */
function extractBackendMessage(text: string): string | null {
  try {
    const parsed: unknown = JSON.parse(text);
    if (typeof parsed === "object" && parsed !== null) {
      const error = (parsed as Record<string, unknown>)["error"];
      if (typeof error === "object" && error !== null) {
        const message = (error as Record<string, unknown>)["message"];
        if (typeof message === "string" && message.length > 0) {
          return message.length > SAFE_MESSAGE_LIMIT
            ? `${message.slice(0, SAFE_MESSAGE_LIMIT)}…`
            : message;
        }
      }
    }
  } catch {
    // Non-JSON body — fall through to the generic message.
  }
  return null;
}

export class HttpBackendApiClient {
  private readonly baseUrl: URL;
  private readonly token: string | null;
  private readonly sessionId: string;
  private readonly requestId: () => string;
  private readonly fetchImpl: typeof fetch;
  private readonly now: () => number;

  constructor(deps: ClientDeps) {
    if (!isLoopbackHttpUrl(deps.baseUrl)) {
      throw new Error(
        `API origin must be a loopback http(s) URL, got '${deps.baseUrl.toString()}'`,
      );
    }
    this.baseUrl = deps.baseUrl;
    this.token = deps.token;
    this.sessionId = deps.sessionId;
    this.requestId = deps.requestId ?? (() => globalThis.crypto.randomUUID());
    this.fetchImpl = deps.fetchImpl ?? globalThis.fetch.bind(globalThis);
    this.now = deps.now ?? (() => Date.now());
  }

  /** GET /api/health (unauthenticated). Measures latency honestly. */
  async getHealth(timeoutMs = DEFAULT_HEALTH_TIMEOUT_MS): Promise<IpcResult<HealthCheck>> {
    const started = this.now();
    const result = await this.requestJson<HealthSnapshot>("/api/health", timeoutMs, isHealthSnapshot);
    if (!result.ok) return result;
    return ipcOk<HealthCheck>({
      snapshot: result.data,
      latencyMs: Math.max(0, Math.round(this.now() - started)),
      checkedAt: new Date().toISOString(),
    });
  }

  /** GET /api/system-info (authenticated, read-only tool). */
  async getSystemInfo(
    timeoutMs = DEFAULT_SYSTEM_INFO_TIMEOUT_MS,
  ): Promise<IpcResult<SystemInfoSummary>> {
    if (!this.token) {
      return ipcError(
        "AUTH_NOT_CONFIGURED",
        "Backend authentication is not configured (JARVIS_API_TOKEN).",
      );
    }
    const result = await this.requestJson<SystemInfoWire>(
      "/api/system-info",
      timeoutMs,
      isSystemInfoResult,
    );
    if (!result.ok) return result;
    return ipcOk<SystemInfoSummary>(toSummary(result.data));
  }

  private async requestJson<T>(
    path: string,
    timeoutMs: number,
    narrow: (value: unknown) => value is T,
  ): Promise<IpcResult<T>> {
    const url = new URL(path, this.baseUrl);
    const headers = buildRequestHeaders(this.token, this.sessionId, this.requestId());
    let response: Response;
    try {
      response = await this.fetchImpl(url, {
        method: "GET",
        headers,
        signal: AbortSignal.timeout(timeoutMs),
      });
    } catch (error) {
      return failureFromException(error);
    }

    if (!response.ok) {
      const body = await response.text().catch(() => "");
      const backendMessage = extractBackendMessage(body);
      return ipcError(
        "HTTP_STATUS",
        backendMessage ?? `Backend returned HTTP ${response.status}.`,
        response.status,
      );
    }

    let parsed: unknown;
    try {
      parsed = await response.json();
    } catch (error) {
      return ipcError("UNEXPECTED", `Backend returned malformed JSON: ${safeMessage(error)}`);
    }
    if (!narrow(parsed)) {
      return ipcError("UNEXPECTED", "Backend response did not match the documented contract.");
    }
    return ipcOk(parsed);
  }
}

