/**
 * Chat requests ride the backend's LLM pipeline. The backend bounds
 * provider requests at OLLAMA_TIMEOUT_SECONDS ≤ 600s (Ollama being the
 * slowest legitimate provider); the desktop timeout sits ABOVE that so a
 * genuinely working local provider is never abandoned — a premature
 * timeout would be unrecoverable because chat submissions are never
 * retried automatically.
 */
export const DEFAULT_CHAT_TIMEOUT_MS = 615_000;
export const DEFAULT_CONVERSATIONS_TIMEOUT_MS = 10_000;
export const DEFAULT_HISTORY_TIMEOUT_MS = 15_000;
export const DEFAULT_DELETE_TIMEOUT_MS = 10_000;

/** Backend pagination/history ceilings (app/api/conversations.py). */
const MAX_HISTORY_TURNS = 400;
const MAX_LIST_CONVERSATIONS = 200;

/** Timeline/header bounds mirrored from the backend contracts. */
const MAX_ACTION_ARGUMENTS = 32;
const MAX_PLAN_STEPS = 32;
const MAX_TEXT_LENGTH = 20_000; // defense-in-depth: reject pathological fields
const SAFE_MESSAGE_LIMIT = 200;

const EXCHANGE_STATUSES: ReadonlySet<string> = new Set([
  "success",
  "action_proposed",
  "plan_proposed",
]);
const RISK_LEVELS: ReadonlySet<string> = new Set(["READ_ONLY", "LOW_RISK", "HIGH_RISK"]);
const APPROVAL_STATUSES: ReadonlySet<string> = new Set([
  "PENDING",
  "APPROVED",
  "REJECTED",
  "EXPIRED",
  "EXECUTED",
]);
const PLAN_STEP_STATUSES: ReadonlySet<string> = new Set([
  "PENDING",
  "AWAITING_APPROVAL",
  "RECOVERY_REQUIRED",
  "COMPLETED",
  "EXECUTED",
  "FAILED",
]);
const TOOL_RESULT_STATUSES: ReadonlySet<string> = new Set([
  "success",
  "already_exists",
  "failure",
]);

/**
 * Pure header builder — the exact header contract the backend expects
 * (backend/app/core/security.py): bearer token + explicit session.
 */
export function buildRequestHeaders(
  token: string | null,
  sessionId: string,
  requestId: string,
): Record<string, string> {
  const headers: Record<string, string> = {
    "X-JARVIS-Session": sessionId,
    "X-Request-ID": requestId,
    Accept: "application/json",
  };
  if (token) headers.Authorization = `Bearer ${token}`;
  return headers;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isBoundedString(value: unknown, max: number): value is string {
  return typeof value === "string" && value.length > 0 && value.length <= max;
}

function isBoundedInt(value: unknown, min: number, max: number): value is number {
  return (
    typeof value === "number" &&
    Number.isInteger(value) &&
    value >= min &&
    value <= max
  );
}

/** True when a JSON object looks like the documented health payload. */
export function isHealthSnapshot(value: unknown): value is HealthSnapshot {
  if (!isRecord(value)) return false;
  return (
    typeof value["name"] === "string" &&
    value["name"].length > 0 &&
    typeof value["status"] === "string" &&
    value["status"].length > 0 &&
    typeof value["version"] === "string" &&
    value["version"].length > 0
  );
}

/** True when a JSON object matches the documented ToolResult shape (wire names). */
type SystemInfoWire = {
  tool_name: string;
  status: "success" | "already_exists" | "failure";
  success: boolean;
  message: string;
  data: Record<string, string> | null;
  timestamp: string;
};

export function isSystemInfoResult(value: unknown): value is SystemInfoWire {
  if (!isRecord(value)) return false;
  const status = value["status"];
  if (
    !isBoundedString(value["tool_name"], 64) ||
    (status !== "success" && status !== "already_exists" && status !== "failure") ||
    typeof value["success"] !== "boolean" ||
    typeof value["message"] !== "string" ||
    typeof value["timestamp"] !== "string"
  ) {
    return false;
  }
  const data = value["data"];
  if (data === null || data === undefined) return true;
  if (!isRecord(data)) return false;
  const entries = Object.entries(data);
  if (entries.length > 32) return false;
  return entries.every(([key, item]) => typeof key === "string" && typeof item === "string");
}

function toSummary(raw: SystemInfoWire): SystemInfoSummary {
  return {
    toolName: raw.tool_name,
    status: raw.status,
    success: raw.success,
    message: raw.message,
    data: raw.data ?? null,
    timestamp: raw.timestamp,
  };
}

