/**
 * Backend API client — MAIN PROCESS ONLY.
 *
 * Every renderer request travels through IPC to this module. It:
 *  - talks ONLY to a validated loopback http(s) origin (net.ts),
 *  - attaches the bearer token and the explicit session header in the
 *    main process (the token never crosses the IPC bridge),
 *  - sends no Origin header (native client; backend require_safe_origin
 *    treats absent Origin as allowed),
 *  - bounds every call with a wall-clock timeout (AbortSignal),
 *  - maps failures to the shared IpcResult envelope with honest codes,
 *  - validates response shapes before anything reaches the renderer,
 *  - NEVER retries: one attempt per request, the result is the truth.
 *
 * Full response types come from the committed OpenAPI snapshot
 * (electron/main/api/schema.gen.ts, generated by `npm run generate:api`).
 * Wire shapes are narrowed here and projected into the camelCase UI
 * types from shared/ipc-contract.ts before crossing back over IPC.
 */

