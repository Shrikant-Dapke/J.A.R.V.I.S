function toProposedActionView(raw: ProposedActionWire): ProposedActionView {
  const args = raw.arguments ?? null;
  return {
    approvalId: raw.approval_id,
    toolName: raw.tool_name,
    arguments: args && isBoundedArguments(args) ? args : {},
    description: raw.action_description,
    riskLevel: raw.risk_level,
    approvalStatus: raw.approval_status,
    expiresAt: raw.expires_at,
  };
}

function toExecutedActionView(raw: ExecutedActionWire): ExecutedActionView {
  return {
    toolName: raw.tool_name,
    status: raw.status,
    success: raw.success,
    message: raw.message,
  };
}

function toPlanView(raw: TaskPlanWire): PlanProposalView {
  const steps: PlanStepView[] = raw.steps.map((step) => ({
    stepId: step.step_id,
    description: step.description,
    toolName: step.tool_name,
    status: step.status ?? "PENDING",
    dependsOn: step.depends_on ?? [],
    approvalId: step.approval_id ?? null,
  }));
  return { planId: raw.plan_id, goal: raw.goal, steps };
}

/** Narrow ChatExchange from the wire; `nowMs` fills an absent timestamp. */
export function toChatExchange(
  raw: ChatResponseWire,
  nowMs: () => number = () => Date.now(),
): ChatExchange {
  return {
    conversationId: raw.conversation_id,
    status: raw.status,
    reply: raw.response,
    occurredAt: raw.timestamp ?? new Date(nowMs()).toISOString(),
    action: raw.action ? toProposedActionView(raw.action) : null,
    toolResult: raw.tool_result ? toExecutedActionView(raw.tool_result) : null,
    plan: raw.plan ? toPlanView(raw.plan) : null,
  };
}

function toConversationListView(raw: ConversationListWire): ConversationListView {
  return {
    conversations: raw.conversations.map((item) => ({
      conversationId: item.conversation_id,
      createdAt: item.created_at,
      updatedAt: item.updated_at,
      turnCount: item.turn_count,
    })),
    total: raw.total,
  };
}

function toConversationHistoryView(raw: ConversationHistoryWire): ConversationHistoryView {
  const turns: ConversationTurnView[] = raw.turns.map((turn) => ({
    role: turn.role,
    content: turn.content,
    timestamp: turn.timestamp,
  }));
  return {
    conversationId: raw.conversation_id,
    turns,
    turnCount: raw.turn_count,
    totalTurnCount: raw.total_turn_count,
  };
}

/** Clamp any exception text into a bounded, safe message. */
function safeMessage(error: unknown): string {
  const text =
    error instanceof Error ? error.message : typeof error === "string" ? error : "unknown error";
  return text.length > SAFE_MESSAGE_LIMIT ? `${text.slice(0, SAFE_MESSAGE_LIMIT)}…` : text;
}

function failureFromException(error: unknown): IpcResult<never> {
  if (error instanceof Error && error.name === "AbortError") {
    return ipcError("TIMEOUT", "The backend did not respond in time.");
  }
  if (error instanceof TypeError) {
    return ipcError("BACKEND_UNREACHABLE", "JARVIS backend is unreachable.");
  }
  return ipcError("UNEXPECTED", `Unexpected client failure: ${safeMessage(error)}`);
}

/** Extract the backend's structured error message (bounded, no internals). */
function extractBackendMessage(text: string): string | null {
  try {
    const parsed: unknown = JSON.parse(text);
    if (isRecord(parsed) && isRecord(parsed["error"])) {
      const message = parsed["error"]["message"];
      if (typeof message === "string" && message.length > 0) {
        return message.length > SAFE_MESSAGE_LIMIT
          ? `${message.slice(0, SAFE_MESSAGE_LIMIT)}…`
          : message;
      }
    }
  } catch {
    // Non-JSON body — fall through to the generic message.
  }
  return null;
}

type RequestOptions = {
  method?: "GET" | "POST" | "DELETE";
  body?: unknown;
};

export class HttpBackendApiClient {
  private readonly baseUrl: URL;
  private readonly token: string | null;
  private readonly sessionId: string;
  private readonly requestId: () => string;
  private readonly fetchImpl: typeof fetch;
  private readonly now: () => number;

  constructor(deps: ClientDeps) {
    if (!isLoopbackHttpUrl(deps.baseUrl)) {
      throw new Error(
        `API origin must be a loopback http(s) URL, got '${deps.baseUrl.toString()}'`,
      );
    }
    this.baseUrl = deps.baseUrl;
    this.token = deps.token;
    this.sessionId = deps.sessionId;
    this.requestId = deps.requestId ?? (() => globalThis.crypto.randomUUID());
    this.fetchImpl = deps.fetchImpl ?? globalThis.fetch.bind(globalThis);
    this.now = deps.now ?? (() => Date.now());
  }

  /** True when every protected route is usable (token attached in main). */
  private requireAuth(): IpcResult<never> | null {
    if (this.token) return null;
    return ipcError(
      "AUTH_NOT_CONFIGURED",
      "Backend authentication is not configured (JARVIS_API_TOKEN).",
    );
  }

  /** GET /api/health (unauthenticated). Measures latency honestly. */
  async getHealth(timeoutMs = DEFAULT_HEALTH_TIMEOUT_MS): Promise<IpcResult<HealthCheck>> {
    const started = this.now();
    const result = await this.requestJson<HealthSnapshot>("/api/health", timeoutMs, isHealthSnapshot);
    if (!result.ok) return result;
    return ipcOk<HealthCheck>({
      snapshot: result.data,
      latencyMs: Math.max(0, Math.round(this.now() - started)),
      checkedAt: new Date().toISOString(),
    });
  }

  /** GET /api/system-info (authenticated, read-only tool). */
  async getSystemInfo(
    timeoutMs = DEFAULT_SYSTEM_INFO_TIMEOUT_MS,
  ): Promise<IpcResult<SystemInfoSummary>> {
    const auth = this.requireAuth();
    if (auth) return auth;
    const result = await this.requestJson<SystemInfoWire>(
      "/api/system-info",
      timeoutMs,
      isSystemInfoResult,
    );
    if (!result.ok) return result;
    return ipcOk<SystemInfoSummary>(toSummary(result.data));
  }

  /** POST /api/chat — one attempt, never retried. */
  async sendChat(
    payload: { message: string; conversationId: string | null },
    timeoutMs = DEFAULT_CHAT_TIMEOUT_MS,
  ): Promise<IpcResult<ChatExchange>> {
    const auth = this.requireAuth();
    if (auth) return auth;
    // The IPC layer validated semantics; this bound is the wire contract.
    if (payload.message.length > CHAT_MESSAGE_MAX_LENGTH) {
      return ipcError("UNEXPECTED", "Internal error: chat message exceeds the contract limit.");
    }
    const body: { message: string; conversation_id?: string } = { message: payload.message };
    if (payload.conversationId) body.conversation_id = payload.conversationId;
    const result = await this.requestJson<ChatResponseWire>(
      "/api/chat",
      timeoutMs,
      isChatResponseWire,
      { method: "POST", body },
    );
    if (!result.ok) return result;
    return ipcOk<ChatExchange>(toChatExchange(result.data, this.now));
  }

  /** GET /api/conversations — metadata page (never message content). */
  async listConversations(
    payload: ConversationListPayload = {},
    timeoutMs = DEFAULT_CONVERSATIONS_TIMEOUT_MS,
  ): Promise<IpcResult<ConversationListView>> {
    const auth = this.requireAuth();
    if (auth) return auth;
    const limit = payload.limit ?? CONVERSATION_LIST_LIMITS.default;
    const offset = payload.offset ?? 0;
    const query = new URLSearchParams({ limit: String(limit), offset: String(offset) });
    const result = await this.requestJson<ConversationListWire>(
      `/api/conversations?${query.toString()}`,
      timeoutMs,
      isConversationListWire,
    );
    if (!result.ok) return result;
    return ipcOk<ConversationListView>(toConversationListView(result.data));
  }

  /** GET /api/conversations/{id} — windowed, chronological history. */
  async getConversation(
    payload: { conversationId: string },
    timeoutMs = DEFAULT_HISTORY_TIMEOUT_MS,
  ): Promise<IpcResult<ConversationHistoryView>> {
    const auth = this.requireAuth();
    if (auth) return auth;
    if (!CONVERSATION_ID_PATTERN.test(payload.conversationId)) {
      return ipcError("UNEXPECTED", "Internal error: invalid conversation identifier.");
    }
    const path = `/api/conversations/${encodeURIComponent(
      payload.conversationId,
    )}?limit=${MAX_HISTORY_TURNS}`;
    const result = await this.requestJson<ConversationHistoryWire>(path, timeoutMs, isConversationHistoryWire);
    if (!result.ok) return result;
    return ipcOk<ConversationHistoryView>(toConversationHistoryView(result.data));
  }

  /** DELETE /api/conversations/{id} — deletes THIS identity's conversation. */
  async deleteConversation(
    payload: { conversationId: string },
    timeoutMs = DEFAULT_DELETE_TIMEOUT_MS,
  ): Promise<IpcResult<ConversationDeletedView>> {
    const auth = this.requireAuth();
    if (auth) return auth;
    if (!CONVERSATION_ID_PATTERN.test(payload.conversationId)) {
      return ipcError("UNEXPECTED", "Internal error: invalid conversation identifier.");
    }
    const path = `/api/conversations/${encodeURIComponent(payload.conversationId)}`;
    const result = await this.requestJson<ConversationClearWire>(
      path,
      timeoutMs,
      isConversationClearWire,
      { method: "DELETE" },
    );
    if (!result.ok) return result;
    return ipcOk<ConversationDeletedView>({ conversationId: result.data.conversation_id });
  }

  private async requestJson<T>(
    path: string,
    timeoutMs: number,
    narrow: (value: unknown) => value is T,
    options: RequestOptions = {},
  ): Promise<IpcResult<T>> {
    const url = new URL(path, this.baseUrl);
    const headers = buildRequestHeaders(this.token, this.sessionId, this.requestId());
    const method = options.method ?? "GET";
    let body: string | undefined;
    if (options.body !== undefined) {
      headers["Content-Type"] = "application/json";
      body = JSON.stringify(options.body);
    }
    let response: Response;
    try {
      response = await this.fetchImpl(url, {
        method,
        headers,
        body,
        signal: AbortSignal.timeout(timeoutMs),
      });
    } catch (error) {
      return failureFromException(error);
    }

    if (!response.ok) {
      const responseBody = await response.text().catch(() => "");
      const backendMessage = extractBackendMessage(responseBody);
      return ipcError(
        "HTTP_STATUS",
        backendMessage ?? `Backend returned HTTP ${response.status}.`,
        response.status,
      );
    }

    let parsed: unknown;
    try {
      parsed = await response.json();
    } catch (error) {
      return ipcError("UNEXPECTED", `Backend returned malformed JSON: ${safeMessage(error)}`);
    }
    if (!narrow(parsed)) {
      return ipcError("UNEXPECTED", "Backend response did not match the documented contract.");
    }
    return ipcOk(parsed);
  }
}

