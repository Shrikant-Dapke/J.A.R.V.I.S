type SystemInfoWire = {
  tool_name: string;
  status: "success" | "already_exists" | "failure";
  success: boolean;
  message: string;
  data: Record<string, string> | null;
  timestamp: string;
};

export function isSystemInfoResult(value: unknown): value is SystemInfoWire {
  if (!isRecord(value)) return false;
  const status = value["status"];
  if (
    !isBoundedString(value["tool_name"], 64) ||
    (status !== "success" && status !== "already_exists" && status !== "failure") ||
    typeof value["success"] !== "boolean" ||
    typeof value["message"] !== "string" ||
    typeof value["timestamp"] !== "string"
  ) {
    return false;
  }
  const data = value["data"];
  if (data === null || data === undefined) return true;
  if (!isRecord(data)) return false;
  const entries = Object.entries(data);
  if (entries.length > 32) return false;
  return entries.every(([key, item]) => typeof key === "string" && typeof item === "string");
}

function toSummary(raw: SystemInfoWire): SystemInfoSummary {
  return {
    toolName: raw.tool_name,
    status: raw.status,
    success: raw.success,
    message: raw.message,
    data: raw.data ?? null,
    timestamp: raw.timestamp,
  };
}

